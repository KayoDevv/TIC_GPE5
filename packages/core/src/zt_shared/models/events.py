from datetime import datetime
from typing import Any, List, Literal, Optional
from uuid import UUID

from pydantic import BaseModel, Field


class EmailContext(BaseModel):
    # Untrusted, attacker-controlled, and possibly injection-neutralised by the
    # sandbox: kept as str (not EmailStr) so a malformed From cannot crash a
    # consumer parsing the event.
    sender: str
    subject: str
    body_text: str = Field(description="Email body content for the LLM")


class FileRequestedEvent(BaseModel):
    job_id: UUID = Field(description="Unique ID of the analysis request")
    s3_url: str = Field(
        description="Presigned S3 URL or path of the file to analyze in the bucket"
    )
    sha256: str = Field(
        pattern=r"^[A-Fa-f0-9]{64}$",
        description="SHA-256 fingerprint of the file",
    )
    email_context: EmailContext
    timestamp: datetime


class MlLayerResultEvent(BaseModel):
    job_id: UUID
    risk_score: int = Field(
        ge=0, le=100, description="Risk score computed by the static ML model"
    )
    static_tags: List[str] = Field(
        description="Tags such as 'packer_detected', 'high_entropy', 'known_malware'"
    )
    processing_time_ms: Optional[int] = Field(
        default=None, description="Processing time in ms (SLA < 500ms)"
    )
    timestamp: datetime


class Ioc(BaseModel):
    type: Literal[
        "ip", "domain", "file_hash", "registry_key", "syscall", "pdf_indicator"
    ]
    value: str
    mitre_tactic: Optional[str] = Field(
        default=None, description="MITRE ATT&CK tactic (e.g. TA0011, TA0002)"
    )
    description: Optional[str] = None


class AnalysisTrust(BaseModel):
    liveness_ok: Optional[bool] = None
    low_observability: Optional[str] = Field(
        default=None,
        description="Reason the run is a probable miss (no_liveness, quiet_benign), else null",
    )
    timeout_triggered: bool = False
    error: Optional[str] = None


class SandboxSignal(BaseModel):
    name: str
    score: Optional[float] = Field(
        default=None, description="null when the hypothesis was skipped (early-exit)"
    )
    weight: float
    fired: bool
    evaluated: bool


class SandboxLayerResultEvent(BaseModel):
    job_id: UUID
    verdict: Optional[Literal["benign", "needs_more_context", "malicious", "error"]] = (
        Field(default=None, description="3-band sandbox verdict; the LLM resolves needs_more_context")
    )
    anomaly_score: Optional[float] = Field(default=None, ge=0.0, le=1.0)
    analysis_trust: Optional[AnalysisTrust] = None
    signals: List[SandboxSignal] = Field(
        default_factory=list, description="Per-hypothesis breakdown"
    )
    iocs: List[Ioc] = Field(description="List of Indicators of Compromise")
    behavior_summary: str = Field(
        description="Raw behavior summary for ingestion by the LLM"
    )
    email_context: EmailContext = Field(
        description="Pass-through of the email context from the request for the LLM Layer"
    )
    timeout_triggered: bool = False
    timestamp: datetime


class LlmLayerResultEvent(BaseModel):
    job_id: UUID
    is_malicious: bool = Field(description="Binary decision Malicious/Clean")
    explanation_text: str = Field(
        description="Natural-language explanation for the Frontend UI"
    )
    confidence_score: Optional[int] = Field(default=None, ge=0, le=100)
    timestamp: datetime


class TechnicalSummary(BaseModel):
    ml_layer_score: Optional[int] = None
    sandbox_layer_iocs: Optional[List[dict[str, Any]]] = None
    sandbox_layer_timeout: Optional[bool] = None
    llm_layer_malicious: Optional[bool] = None


class VerdictResultEvent(BaseModel):
    job_id: UUID = Field(description="Unique ID of the analysis request")
    final_decision: Literal["allowed", "blocked", "warning"] = Field(
        description="Final decision to be applied by the Frontend"
    )
    user_explanation: Optional[str] = Field(
        default=None,
        description=(
            "Explanatory text generated by the LLM Layer (if available)"
            " or a default one on a Sandbox timeout"
        ),
    )
    technical_summary: Optional[TechnicalSummary] = Field(
        default=None, description="Summary of the data that led to the decision"
    )
    timestamp: datetime
